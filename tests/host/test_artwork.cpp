HOST_TEST(artwork_ink_density_falls_as_the_source_brightens) {
  app_core::MediaArtwork art;
  EXPECT_TRUE(airplay::decode_artwork(kBandsJpeg, sizeof(kBandsJpeg), art));

  // Interiors only. JPEG rings at a hard edge and error diffusion carries a
  // band's residue into the next few rows of the one below, so the boundaries
  // are legitimately mixed - asserting on them would be asserting that two
  // correct behaviours do not happen.
  const int band = art.height / 3;
  const int margin = band / 4;
  const double dark = ink_density(art, margin, band - margin);
  const double mid = ink_density(art, band + margin, 2 * band - margin);
  const double light = ink_density(art, 2 * band + margin, art.height - margin);

  // The ordering is the real assertion: strictly monotonic, which is what
  // "brighter means fewer ink pixels" means and what a scrambled decode cannot
  // accidentally satisfy across three bands.
  EXPECT_TRUE(dark > mid);
  EXPECT_TRUE(mid > light);

  // Absolute bounds too, loose. Monotonic alone would pass for a pipeline that
  // had crushed all three bands into nearly-black, which is a real failure mode
  // for a 1-bit panel and the one that reads as "the picture is a smudge".
  // Source levels are 16/128/240 of 255, so ink should land near 0.94/0.50/0.06.
  EXPECT_TRUE(dark > 0.80);
  EXPECT_TRUE(mid > 0.30 && mid < 0.70);
  EXPECT_TRUE(light < 0.20);
}

HOST_TEST(artwork_mid_grey_dithers_rather_than_thresholds) {
  app_core::MediaArtwork art;
  EXPECT_TRUE(airplay::decode_artwork(kBandsJpeg, sizeof(kBandsJpeg), art));

  // Every row of the mid band must be part ink and part paper. A threshold
  // sends a flat 128 field entirely one way or the other, and it does so
  // per-row - which is invisible in a whole-band average that a mixture of
  // solid-black and solid-white rows would satisfy just as well.
  const int band = art.height / 3;
  const int stride = (art.width + 7) / 8;
  int mixed_rows = 0;
  for (int y = band + band / 4; y < 2 * band - band / 4; ++y) {
    int set = 0;
    for (int x = 0; x < art.width; ++x) {
      if (art.bits[y * stride + (x >> 3)] & (0x80u >> (x & 7))) ++set;
    }
    if (set > 0 && set < art.width) ++mixed_rows;
  }
  const int rows = (2 * band - band / 4) - (band + band / 4);
  EXPECT_EQ(mixed_rows, rows);
}

HOST_TEST(artwork_rejects_input_it_cannot_decode) {
  app_core::MediaArtwork art;
  EXPECT_TRUE(!airplay::decode_artwork(nullptr, 0, art));
  EXPECT_TRUE(art.bits == nullptr);

  // Not a JPEG at all. `art` must be left exactly as it was rather than
  // pointed at a half-filled buffer: render_now_playing.cpp decides whether to
  // draw a cover from `bits != nullptr`, so a failed decode that set it would
  // paint whatever the allocation happened to contain.
  const unsigned char garbage[64] = {0};
  EXPECT_TRUE(!airplay::decode_artwork(garbage, sizeof(garbage), art));
  EXPECT_TRUE(art.bits == nullptr);

  // Truncated: a real JPEG header, no image data. jd_prepare() may well accept
  // this and jd_decomp() then fail, which is a different code path from the two
  // above and the one a dropped RTSP body actually produces.
  EXPECT_TRUE(!airplay::decode_artwork(kBandsJpeg, 200, art));
  EXPECT_TRUE(art.bits == nullptr);
}

