// Does a decoded cover actually look like the picture that was sent?
//
// This suite exists because the answer was no, on hardware, for a build that
// showed a cover and logged a clean decode. `JD_FORMAT 2` (grayscale) selected
// a branch LVGL had deleted from the vendored tjpgd, so tjpgd handed back
// jd->workbuf still holding block_idct() scratch. The shapes were faintly
// there - IDCT scratch correlates with the image - so nothing about the panel,
// and nothing in the log, said "wrong". Only a person looking at it did.
//
// So the property under test is the one a person was checking by eye: **ink
// density falls as the source gets brighter**. That is what a grayscale
// rendering on a 1-bit panel means, and it is false for every way this pipeline
// has been wrong so far - garbage pixels, inverted polarity, a threshold in
// place of a dither.
//
// Deliberately not a golden-bitmap comparison. Changing the dither kernel or
// the downsample is legitimate work, and a golden file would fail for that
// while still passing for a JPEG decoded into noise - the exact wrong way
// round.

